export const LANGS = Object.keys(STRINGS);

export function strings(lang) {
  const l = String(lang || '').toLowerCase();
  if (l.startsWith('zh')) return STRINGS[/tw|hk|mo|hant/.test(l) ? 'zh-TW' : 'zh-CN'];
  return STRINGS[l.slice(0, 2)] ?? STRINGS.en;
}
